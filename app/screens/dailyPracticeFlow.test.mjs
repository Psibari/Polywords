import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read = path => readFileSync(new URL(path, import.meta.url), 'utf8');
const screen = read('./DailyChallengeScreen.tsx');
const practice = read('../components/DailyPracticeIntro.tsx');
const storage = read('../constants/storageKeys.ts');
assert.match(storage, /DAILY_PRACTICE_SEEN_KEY/);
assert.match(screen, /practice === 'true' \|\| seen === 'true'/, 'existing Daily users skip forced practice');
assert.match(screen, /isReadyToStart && \(!practiceSeen \|\| practiceReplay\)/);
assert.match(screen, /<DailyPracticeIntro onComplete=/);
assert.match(screen, /REPLAY PRACTICE/);
assert.match(practice, /onClaim=\{claim\}/, 'practice uses actual swipe-claim component');
assert.match(practice, /setClueCount\(count => Math\.min\(3, count \+ 1\)\)/);
assert.match(practice, /setWrong\(previous => \[\.\.\.previous, word\]\)/);
assert.doesNotMatch(practice, /startDailyChallenge|claimDailyWord|useGameStore|grantGoldFeather|DAILY_INTRO_SEEN_KEY/, 'practice must not mutate real Daily');
assert.match(screen, /onPress=\{\(\) => void handleStartDaily\(\)\}/, 'real Daily still starts only from its own gate');
console.log('Daily practice isolation and entry wiring checks passed');
